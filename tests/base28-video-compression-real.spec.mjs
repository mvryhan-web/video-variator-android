import {test,expect} from '@playwright/test';
import {existsSync,promises as fs} from 'node:fs';

const fixture='tests/fixtures/video-compress-tiny.mp4';

// Dedicated workflow generates this tiny rights-free synthetic source with FFmpeg.
// Running ordinary unit/UI Playwright suites without the fixture skips the
// expensive actual WASM encode; do not call the mock adapter a real transcoding test.
test('BASE #28: actual local FFmpeg/WASM encodes a valid downloadable H.264 MP4',async({page})=>{
 test.skip(test.info().project.name!=='chromium','Single real codec smoke on Chromium only');
 test.skip(!existsSync(fixture),'Synthetic MP4 must be generated by dedicated CI');
 test.setTimeout(120000);
 let uploadCalls=0;
 page.on('request',r=>{if(r.method()==='POST')uploadCalls++;});
 await page.goto('/mobile-utility.html?tool=video-compress');
 await expect(page.locator('#videoCompressQuality')).toBeVisible();
 await page.locator('#videoCompressQuality').selectOption('balanced');
 await page.locator('#utilityFiles').setInputFiles(fixture);
 await page.locator('#utilityRun').click();
 await expect(page.locator('#utilityResults .utility-result')).toBeVisible({timeout:90000});
 await expect(page.locator('#utilityStatus')).toContainText('Ready',{timeout:90000});
 await expect(page.locator('.utility-size-note')).toContainText('Original');
 const pending=page.waitForEvent('download');
 await page.locator('#utilityResults .utility-result button').click();
 const download=await pending;
 expect(download.suggestedFilename()).toBe('video-compress-tiny-compressed.mp4');
 const bytes=await fs.readFile(await download.path());
 expect(bytes.byteLength).toBeGreaterThan(500);
 expect(bytes.subarray(4,8).toString('ascii')).toBe('ftyp');
 expect(uploadCalls).toBe(0);
});
