test('MOCK WORKER: enforces repeated submission / idempotency guard', async () => {
  const plan = makeValidPlan(['m1', 'm2'], 'shared-plan-token');
  const adapters = async () => ({ text: 'ok' });

  // First submission succeeds
  const res1 = await executeCompareAiMock(plan, { adapters });
  assert.equal(res1.success, true);

  // Second submission with same plan object rejects
  await assert.rejects(() => executeCompareAiMock(plan, { adapters }), /REPEATED_SUBMISSION_DISALLOWED/);

  // Second submission with new plan object but same ID rejects
  const duplicateIdPlan = makeValidPlan(['m1', 'm2'], 'shared-plan-token');
  await assert.rejects(() => executeCompareAiMock(duplicateIdPlan, { adapters }), /REPEATED_SUBMISSION_DISALLOWED/);
});
