import test from 'node:test';
import assert from 'node:assert/strict';
import { executeCompareAiMock, runCompareAiMockWorker } from '../server/compare-ai-mock-worker.js';

function makeValidPlan(candidates = ['openai-gpt4o', 'gemini-15-pro'], id = null) {
  return {
    valid: true,
    id: id || `plan-${Math.random().toString(36).slice(2)}`,
    kind: 'text',
    candidateCount: candidates.length,
    candidates: candidates.map(c => typeof c === 'string' ? { id: c, provider: 'mock-provider' } : c),
    executionPolicy: {
      boundedConcurrencyLimit: 2,
      allowPartialFailure: true
    }
  };
}

test('MOCK WORKER: executes 2, 3, and 4 candidates and preserves result order', async () => {
  for (const count of [2, 3, 4]) {
    const allModels = ['openai-gpt4o', 'gemini-15-pro', 'claude-35-sonnet', 'mistral-large'];
    const candidates = allModels.slice(0, count);
    const plan = makeValidPlan(candidates);

    // Adapters finish with varying delays to test order preservation
    const adapters = {};
    candidates.forEach((modelId, idx) => {
      adapters[modelId] = async () => {
        const delay = (count - idx) * 10; // First candidate takes longest
        await new Promise(r => setTimeout(r, delay));
        return { text: `Generated by ${modelId}` };
      };
    });

    const res = await runCompareAiMockWorker(plan, adapters);

    assert.equal(res.success, true);
    assert.equal(res.status, 'completed');
    assert.equal(res.candidates.length, count);
    assert.equal(res.summary.total, count);
    assert.equal(res.summary.fulfilled, count);

    // Verify ordering matches original candidate array order exactly
    res.candidates.forEach((c, idx) => {
      assert.equal(c.candidateId, candidates[idx]);
      assert.equal(c.status, 'fulfilled');
      assert.equal(c.result.text, `Generated by ${candidates[idx]}`);
    });
  }
});

test('MOCK WORKER: respects bounded concurrency upper bound', async () => {
  const candidates = ['m1', 'm2', 'm3', 'm4'];
  const plan = makeValidPlan(candidates);

  let activeCount = 0;
  let maxActive = 0;

  const adapters = async (cand) => {
    activeCount++;
    if (activeCount > maxActive) maxActive = activeCount;
    await new Promise(r => setTimeout(r, 20));
    activeCount--;
    return { output: `done-${cand.id || cand}` };
  };

  const res = await executeCompareAiMock(plan, {
    adapters,
    concurrency: 2
  });

  assert.equal(res.success, true);
  assert.equal(res.summary.fulfilled, 4);
  assert.ok(maxActive <= 2, `Peak active concurrency ${maxActive} should not exceed bound 2`);
});

test('MOCK WORKER: handles partial failure honest reporting without erasing success', async () => {
  const plan = makeValidPlan(['good-model', 'bad-model', 'slow-model']);

  const adapters = {
    'good-model': async () => ({ text: 'good output' }),
    'bad-model': async () => { throw new Error('PROVIDER_RATE_LIMIT'); },
    'slow-model': async () => ({ text: 'slow output' })
  };

  const res = await runCompareAiMockWorker(plan, adapters);

  assert.equal(res.success, true); // at least 1 fulfilled
  assert.equal(res.status, 'partial_success');
  assert.equal(res.summary.total, 3);
  assert.equal(res.summary.fulfilled, 2);
  assert.equal(res.summary.failed, 1);

  assert.equal(res.candidates[0].status, 'fulfilled');
  assert.equal(res.candidates[0].result.text, 'good output');

  assert.equal(res.candidates[1].status, 'failed');
  assert.equal(res.candidates[1].error, 'PROVIDER_RATE_LIMIT');
  assert.equal(res.candidates[1].result, null);

  assert.equal(res.candidates[2].status, 'fulfilled');
  assert.equal(res.candidates[2].result.text, 'slow output');
});

